// Имя ноды: правила те же, что на сервере (DNS-метка в нижнем регистре), и
// подсказка, которая делает из написанного человеком годное имя. Лежит
// отдельно, потому что имя задаётся в двух местах - при добавлении и при
// переименовании в карточке.
export const NODE_NAME_RE = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/

const RU: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
}

// Из того, что человек написал, делаем имя, которое примет сеть: нижний регистр,
// кириллица транслитом, всё прочее - дефис. Пустую строку не предлагаем.
export function suggestNodeName(raw: string): string {
  const out = raw
    .trim()
    .toLowerCase()
    .split('')
    .map((ch) => (ch in RU ? RU[ch] : ch))
    .join('')
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 63)
    .replace(/-+$/g, '')
  return NODE_NAME_RE.test(out) ? out : ''
}

